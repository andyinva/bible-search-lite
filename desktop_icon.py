#!/usr/bin/env python3
"""
desktop_icon.py - Put a Bible Search Lite start icon on the desktop.

This little tool works out where Bible Search Lite is installed (the
folder this file lives in) and which environment it is running in, then
places a start icon on the matching desktop:

    * Native Windows      -> a .lnk shortcut on the Windows desktop
    * WSL (Ubuntu inside  -> a launcher .bat in the install folder and
      Windows)               a .lnk shortcut on the WINDOWS desktop
    * Native Linux/Ubuntu -> a .desktop launcher on the Linux desktop

That is all it does. Run it once right after installing:

    python3 desktop_icon.py

or click "Create Desktop Icon" in the program's Settings menu.

Author: Andrew Hopkins
"""

import os
import sys
import shutil
import subprocess

# The display name used for the desktop icon in every environment
APP_NAME = "Bible Search Lite"

# The main program file the icon must start
MAIN_SCRIPT = "bible_search_lite.py"

# Icon image files expected to sit in the install folder
ICON_ICO = "bible_search_lite.ico"   # used on Windows
ICON_PNG = "bible_search_lite.png"   # used on Linux


# ----------------------------------------------------------------------
# Environment detection helpers
# ----------------------------------------------------------------------

def get_install_dir():
    """
    Return the folder Bible Search Lite is installed in.

    That is simply the folder this file lives in, so the tool keeps
    working no matter where the user placed or moved the program.
    """
    return os.path.dirname(os.path.abspath(__file__))


def detect_environment():
    """
    Work out which environment we are running in.

    Returns:
        str: "windows" (native Windows Python),
             "wsl"     (Linux running inside Windows via WSL), or
             "linux"   (a real Linux machine, e.g. native Ubuntu)
    """
    # Native Windows Python reports "win32"
    if sys.platform.startswith("win"):
        return "windows"

    # WSL kernels identify themselves as Microsoft in /proc/version
    try:
        if os.path.exists("/proc/version"):
            with open("/proc/version") as f:
                if "microsoft" in f.read().lower():
                    return "wsl"
    except Exception:
        pass

    return "linux"


# ----------------------------------------------------------------------
# Native Windows
# ----------------------------------------------------------------------

def _ps_quote(text):
    """
    Quote a string for use inside a single-quoted PowerShell string.
    (In PowerShell a single quote is escaped by doubling it.)
    """
    return text.replace("'", "''")


def create_windows_icon(install_dir):
    """
    Create the desktop shortcut on NATIVE Windows.

    Writes a small launcher batch file into the install folder, then
    asks Windows (through PowerShell) to build a genuine .lnk shortcut
    to it on the desktop. Using Windows' own shortcut engine guarantees
    the icon double-clicks correctly.

    Returns:
        tuple: (success (bool), message (str))
    """
    # Prefer pythonw.exe so no black console window opens with the app
    python_exe = sys.executable
    pythonw = os.path.join(os.path.dirname(python_exe), "pythonw.exe")
    if os.path.exists(pythonw):
        python_exe = pythonw

    # --- Launcher batch file in the install folder -------------------
    bat_path = os.path.join(install_dir, "run_bible_search_native.bat")
    bat_lines = [
        "@echo off",
        "REM %s launcher (native Windows) - generated by desktop_icon.py" % APP_NAME,
        "cd /d \"%~dp0\"",
        "start \"\" \"%s\" %s" % (python_exe, MAIN_SCRIPT),
        "",
    ]
    with open(bat_path, "w", newline="\r\n") as f:
        f.write("\n".join(bat_lines))

    # --- Desktop shortcut via PowerShell -----------------------------
    icon_path = os.path.join(install_dir, ICON_ICO)
    ps_script = (
        "$d=[Environment]::GetFolderPath('Desktop'); "
        "$w=New-Object -ComObject WScript.Shell; "
        "$s=$w.CreateShortcut($d+'\\%s.lnk'); "
        "$s.TargetPath='%s'; "
        "$s.WorkingDirectory='%s'; "
        "%s"
        "$s.WindowStyle=7; "
        "$s.Description='%s'; "
        "$s.Save(); "
        "Write-Output ($d+'\\%s.lnk')"
    ) % (
        _ps_quote(APP_NAME),
        _ps_quote(bat_path),
        _ps_quote(install_dir),
        # Only set the icon when the .ico file is actually there
        ("$s.IconLocation='%s,0'; " % _ps_quote(icon_path)) if os.path.exists(icon_path) else "",
        _ps_quote(APP_NAME),
        _ps_quote(APP_NAME),
    )

    result = subprocess.run(
        ["powershell", "-NoProfile", "-Command", ps_script],
        capture_output=True, text=True, timeout=60
    )
    if result.returncode != 0:
        return False, "Windows could not create the shortcut:\n" + result.stderr.strip()

    return True, "Desktop icon created:\n" + result.stdout.strip()


# ----------------------------------------------------------------------
# WSL (Ubuntu running inside Windows)
# ----------------------------------------------------------------------

def create_wsl_icon(install_dir):
    """
    Create the desktop shortcut when running under WSL.

    The program itself runs in Linux, but the desktop the user sees is
    the WINDOWS desktop, so:
      1. write a launcher .bat in the install folder that starts the
         program through WSL (using this distribution's real name), and
      2. have Windows build a .lnk shortcut to that .bat on the
         Windows desktop (powershell.exe is callable from inside WSL).

    Returns:
        tuple: (success (bool), message (str))
    """
    # Real name of this WSL distribution (e.g. "Ubuntu-24.04").
    distro = os.environ.get("WSL_DISTRO_NAME", "").strip()

    # Windows spelling of the install folder (e.g. C:\Users\...\bible-search-lite)
    win_install = subprocess.run(
        ["wslpath", "-w", install_dir],
        capture_output=True, text=True, timeout=30
    ).stdout.strip()
    if not win_install:
        return False, "Could not translate the install folder to a Windows path."

    # --- Launcher batch file in the install folder -------------------
    # Uses the detected distribution name, with a fallback to the
    # default distribution, and stays open on errors so they can be read.
    distro_flag = ('-d "%s" ' % distro) if distro else ""
    bat_name = "run_bible_search_win.bat"
    bat_path = os.path.join(install_dir, bat_name)
    bat_lines = [
        "@echo off",
        "title %s" % APP_NAME,
        "REM %s launcher (WSL) - generated by desktop_icon.py" % APP_NAME,
        "REM Starts the copy of the program that lives in this folder.",
        "echo Starting %s..." % APP_NAME,
        "wsl %sbash -c \"cd '%s' && python3 %s\"" % (distro_flag, install_dir, MAIN_SCRIPT),
        "if not errorlevel 1 exit /b 0",
        "echo.",
        "echo Trying the default WSL distribution instead...",
        "wsl bash -c \"cd '%s' && python3 %s\"" % (install_dir, MAIN_SCRIPT),
        "if not errorlevel 1 exit /b 0",
        "echo.",
        "echo ERROR: %s could not start. The messages above say why." % APP_NAME,
        "pause",
        "",
    ]
    with open(bat_path, "w", newline="\r\n") as f:
        f.write("\n".join(bat_lines))

    # --- Desktop shortcut via Windows PowerShell ---------------------
    win_bat = win_install.rstrip("\\") + "\\" + bat_name
    win_icon = win_install.rstrip("\\") + "\\" + ICON_ICO
    have_icon = os.path.exists(os.path.join(install_dir, ICON_ICO))

    ps_script = (
        # Clear the 'downloaded from the internet' flag so Windows
        # runs the launcher without complaining (harmless if not set)
        "Get-ChildItem -Path '%s' -ErrorAction SilentlyContinue | Unblock-File; "
        "$d=[Environment]::GetFolderPath('Desktop'); "
        "$w=New-Object -ComObject WScript.Shell; "
        "$s=$w.CreateShortcut($d+'\\%s.lnk'); "
        "$s.TargetPath='%s'; "
        "$s.WorkingDirectory='%s'; "
        "%s"
        "$s.WindowStyle=7; "
        "$s.Description='%s'; "
        "$s.Save(); "
        "Write-Output ($d+'\\%s.lnk')"
    ) % (
        _ps_quote(win_bat),
        _ps_quote(APP_NAME),
        _ps_quote(win_bat),
        _ps_quote(win_install),
        ("$s.IconLocation='%s,0'; " % _ps_quote(win_icon)) if have_icon else "",
        _ps_quote(APP_NAME),
        _ps_quote(APP_NAME),
    )

    # powershell.exe is reachable from WSL through Windows interop.
    # Run it from a Windows-accessible folder to avoid path warnings.
    powershell = shutil.which("powershell.exe") or "/mnt/c/Windows/System32/WindowsPowerShell/v1.0/powershell.exe"
    result = subprocess.run(
        [powershell, "-NoProfile", "-Command", ps_script],
        capture_output=True, text=True, timeout=60,
        cwd="/mnt/c" if os.path.isdir("/mnt/c") else None
    )
    if result.returncode != 0:
        return False, "Windows could not create the shortcut:\n" + result.stderr.strip()

    return True, "Desktop icon created on the Windows desktop:\n" + result.stdout.strip()


# ----------------------------------------------------------------------
# Native Linux (for example a real Ubuntu machine)
# ----------------------------------------------------------------------

def create_linux_icon(install_dir):
    """
    Create the desktop launcher on NATIVE Linux (e.g. Ubuntu).

    Writes a standard freedesktop .desktop file onto the user's
    desktop, pointing at the install folder, and marks it trusted so
    GNOME shows it as a clickable icon rather than a warning.

    Returns:
        tuple: (success (bool), message (str))
    """
    # Find the user's desktop folder. `xdg-user-dir` knows the right
    # answer even when the folder is renamed/localized; fall back to
    # the conventional ~/Desktop.
    desktop_dir = None
    try:
        out = subprocess.run(["xdg-user-dir", "DESKTOP"],
                             capture_output=True, text=True, timeout=15).stdout.strip()
        if out and os.path.isdir(out):
            desktop_dir = out
    except Exception:
        pass
    if not desktop_dir:
        candidate = os.path.join(os.path.expanduser("~"), "Desktop")
        if os.path.isdir(candidate):
            desktop_dir = candidate
    if not desktop_dir:
        return False, "Could not find a Desktop folder in your home directory."

    icon_png = os.path.join(install_dir, ICON_PNG)

    # Standard .desktop launcher. "Path=" sets the working directory so
    # the program finds its databases; "Terminal=false" keeps it clean.
    lines = [
        "[Desktop Entry]",
        "Type=Application",
        "Name=%s" % APP_NAME,
        "Comment=Search multiple English translations of the Bible",
        "Exec=python3 %s" % MAIN_SCRIPT,
        "Path=%s" % install_dir,
        "Terminal=false",
        "Categories=Education;",
    ]
    if os.path.exists(icon_png):
        lines.insert(4, "Icon=%s" % icon_png)

    launcher_path = os.path.join(desktop_dir, "bible-search-lite.desktop")
    with open(launcher_path, "w") as f:
        f.write("\n".join(lines) + "\n")

    # Must be executable to be treated as a launcher
    os.chmod(launcher_path, 0o755)

    # Mark as trusted so GNOME enables it without an "Allow Launching"
    # right-click step. Best effort - not all desktops have gio.
    try:
        subprocess.run(["gio", "set", launcher_path,
                        "metadata::trusted", "true"],
                       capture_output=True, timeout=15)
    except Exception:
        pass

    return True, ("Desktop icon created:\n%s\n\n"
                  "If the icon shows a warning the first time, right-click "
                  "it and choose 'Allow Launching'.") % launcher_path


# ----------------------------------------------------------------------
# Main entry point
# ----------------------------------------------------------------------

def create_desktop_icon():
    """
    Detect the environment and place the start icon on the right desktop.

    Returns:
        tuple: (success (bool), message (str)) - the message is written
               for the user and is shown by the Settings menu button.
    """
    install_dir = get_install_dir()

    # Sanity check: make sure the main program is actually here
    if not os.path.exists(os.path.join(install_dir, MAIN_SCRIPT)):
        return False, ("%s was not found in:\n%s\n\n"
                       "desktop_icon.py must live in the %s install folder."
                       % (MAIN_SCRIPT, install_dir, APP_NAME))

    environment = detect_environment()

    try:
        if environment == "windows":
            return create_windows_icon(install_dir)
        elif environment == "wsl":
            return create_wsl_icon(install_dir)
        else:
            return create_linux_icon(install_dir)
    except Exception as e:
        return False, "Could not create the desktop icon:\n%s" % e


def main():
    """Run from the command line: report what happened and exit."""
    print("=" * 60)
    print("%s - Desktop Icon Creator" % APP_NAME)
    print("=" * 60)
    print("Install folder : %s" % get_install_dir())
    print("Environment    : %s" % detect_environment())
    print()

    success, message = create_desktop_icon()
    print(message)
    print()
    print("Done." if success else "FAILED - see the message above.")
    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()
